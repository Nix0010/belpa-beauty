-- Función auxiliar para generación atómica de números de pedido en servidor
CREATE SEQUENCE IF NOT EXISTS public.order_number_seq START WITH 1 INCREMENT BY 1;

CREATE OR REPLACE FUNCTION public.get_next_order_number()
RETURNS TEXT
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    next_val BIGINT;
    year_str TEXT;
BEGIN
    next_val := nextval('public.order_number_seq');
    year_str := to_char(CURRENT_DATE, 'YYYY');
    RETURN 'BELPA-' || year_str || '-' || lpad(next_val::text, 6, '0');
END;
$$;

